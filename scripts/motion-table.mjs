// The motion table: every animation and transition the built site actually runs, read from
// Chrome's computed styles, so a motion change can be proved by a text diff (pixels can't show
// motion). For each page, once with normal motion and once with reduced motion, it lists:
// element, animation (effective keyframes, duration, delay, easing, iterations) and transition
// (properties, duration, delay, easing), deduplicated with counts.
//
//   pnpm build && pnpm motion:table <out.md> [--pages /,/resume/]
//   diff -u before.md after.md
//
// Keyframes are reported as the definition that WINS on that page: Astro doesn't scope
// @keyframes, so two files defining the same name fight, and the table shows the winner.
import http from "node:http";
import fs from "node:fs";
import path from "node:path";
import { chromium } from "playwright-core";

const argv = process.argv.slice(2);
const arg = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : null; };
const out = argv[0] && !argv[0].startsWith("--") ? path.resolve(argv[0]) : null;
if (!out) { console.error("usage: pnpm motion:table <out.md> [--pages /,/resume/]"); process.exit(2); }
const dist = path.resolve("dist");
if (!fs.existsSync(path.join(dist, "index.html"))) { console.error("dist/ is missing: run pnpm build first"); process.exit(2); }

const PAGES = arg("--pages")?.split(",") ?? [
  "/", "/projects/", "/projects/ghosted/", "/projects/asheville-dispensary/", "/projects/vegavengers/",
  "/projects/daybreak/", "/blog/", "/blog/designing-for-the-second-user/", "/resume/", "/design-system/",
  "/card/", "/404.html",
];

const types = { ".html": "text/html", ".css": "text/css", ".js": "text/javascript", ".mjs": "text/javascript", ".svg": "image/svg+xml", ".png": "image/png", ".webp": "image/webp", ".jpg": "image/jpeg", ".woff2": "font/woff2", ".json": "application/json" };
const server = http.createServer((req, res) => {
  let f = path.join(dist, decodeURIComponent(req.url.split("?")[0]));
  if (fs.existsSync(f) && fs.statSync(f).isDirectory()) f = path.join(f, "index.html");
  if (!fs.existsSync(f)) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { "content-type": types[path.extname(f).toLowerCase()] ?? "application/octet-stream" });
  fs.createReadStream(f).pipe(res);
});
await new Promise((r) => server.listen(0, "127.0.0.1", r));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ channel: "chrome" });

function readMotion() {
  const keyframes = {};
  const walk = (rules) => {
    for (const r of rules) {
      if (r instanceof CSSKeyframesRule) keyframes[r.name] = [...r.cssRules].map((k) => `${k.keyText} { ${k.style.cssText} }`).join(" ");
      else if (r.cssRules) walk(r.cssRules);
    }
  };
  for (const s of document.styleSheets) { try { walk(s.cssRules); } catch {} }
  const label = (el, pe) => {
    const cls = [...el.classList].filter((c) => !c.startsWith("astro-") && !/^svelte-/.test(c)).slice(0, 2);
    return el.tagName.toLowerCase() + (el.id ? `#${el.id}` : "") + cls.map((c) => `.${c}`).join("") + (pe ?? "");
  };
  const rows = {};
  const add = (k) => { rows[k] = (rows[k] ?? 0) + 1; };
  const used = new Set();
  for (const el of document.querySelectorAll("*")) {
    for (const pe of [null, "::before", "::after"]) {
      const cs = getComputedStyle(el, pe);
      if (pe && cs.content === "none") continue;
      if (cs.animationName && cs.animationName !== "none") {
        const names = cs.animationName.split(",").map((n) => n.trim());
        names.forEach((n) => used.add(n));
        // Keyframes that read a custom property (e.g. --enter-distance) resolve it per element.
        const vars = [...new Set(names.flatMap((n) => [...(keyframes[n] ?? "").matchAll(/var\((--[\w-]+)/g)].map((m) => m[1])))];
        const resolved = vars.map((v) => ` ${v}: ${cs.getPropertyValue(v).trim() || "(default)"}`).join(";");
        add(`animation | ${label(el, pe)} | ${cs.animationName}${resolved ? ` [${resolved.trim()}]` : ""} | ${cs.animationDuration} | delay ${cs.animationDelay} | ${cs.animationTimingFunction} | ×${cs.animationIterationCount}`);
      }
      const durs = cs.transitionDuration.split(",").map((d) => parseFloat(d));
      if (durs.some((d) => d > 0)) {
        add(`transition | ${label(el, pe)} | ${cs.transitionProperty} | ${cs.transitionDuration} | delay ${cs.transitionDelay} | ${cs.transitionTimingFunction}`);
      }
    }
  }
  return { rows, keyframes: Object.fromEntries([...used].sort().map((n) => [n, keyframes[n] ?? "(missing)"])) };
}

let md = "# Motion table\n\nGenerated by `scripts/motion-table.mjs` from `dist/`. Rows are `kind | element | what | duration | delay | easing | count`.\n";
for (const reduced of [false, true]) {
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: reduced ? "reduce" : "no-preference", colorScheme: "dark" });
  const page = await ctx.newPage();
  md += `\n## ${reduced ? "Reduced motion" : "Normal motion"}\n`;
  for (const p of PAGES) {
    await page.goto(base + p, { waitUntil: "load" });
    await page.waitForTimeout(200);
    const { rows, keyframes } = await page.evaluate(readMotion);
    md += `\n### ${p}\n\n`;
    for (const k of Object.keys(rows).sort()) md += `- ${k}${rows[k] > 1 ? ` (${rows[k]}×)` : ""}\n`;
    const names = Object.keys(keyframes);
    if (names.length) md += `\nKeyframes that win on this page:\n\n` + names.map((n) => `- \`${n}\`: ${keyframes[n]}`).join("\n") + "\n";
  }
  await ctx.close();
}
await browser.close();
server.close();
fs.writeFileSync(out, md);
console.log(`motion table written: ${out}`);
