// cello.dev design tokens: generator and guards.
//
//   pnpm tokens             write src/styles/tokens.css from src/tokens/tokens.json
//   pnpm tokens --check     fail if tokens.css is stale, or if any file gained a raw value or a
//                           hand-built pattern beyond src/tokens/raw-baseline.json
//                           and fail if tokens.json drifts from the vendored Cello family layer
//                           (src/tokens/family.json); warn only if ~/Documents/code/cello-family
//                           has a newer version, so no build depends on that folder existing
//   pnpm tokens --baseline  rewrite the baseline. Run it only after REMOVING literals, never to
//                           admit a new one: the baseline is a ratchet that only goes down.
//
// The raw-value scan covers every file a page can reach (src/pages, src/content and their imports).
// src/hidden-pages is the parked Lab staging area (DESIGN.md: "hidden until implementations meet
// portfolio quality"), so it and the components only it uses are out of scope until they ship.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const rel = (f) => path.relative(root, f);
const SRC = path.join(root, "src");
const JSON_PATH = path.join(SRC, "tokens/tokens.json");
const CSS_PATH = path.join(SRC, "styles/tokens.css");
const BASELINE_PATH = path.join(SRC, "tokens/raw-baseline.json");
const FAMILY_PATH = path.join(SRC, "tokens/family.json");
const FAMILY_SOURCE = path.join(os.homedir(), "Documents/code/cello-family/family.json");
const flag = (n) => process.argv.includes(n);

// ---------- generator ----------
function generate() {
  const spec = JSON.parse(fs.readFileSync(JSON_PATH, "utf8"));
  const rootLines = [], lightLines = [];
  for (const g of spec.groups) {
    rootLines.push("", `  /* ${g.name} */`);
    let lightHeader = false;
    for (const t of g.tokens) {
      const v = t.$value;
      const doc = t.$description ? ` /* ${t.$description.replace(/\*\//g, "* /")} */` : "";
      if (typeof v === "string") { rootLines.push(`  ${t.css}: ${v};${doc}`); continue; }
      rootLines.push(`  ${t.css}: ${v.dusk ?? v.dark};${doc}`);
      if (!lightHeader) { lightLines.push("", `  /* ${g.name} */`); lightHeader = true; }
      lightLines.push(`  ${t.css}: ${v.day ?? v.light};`);
    }
  }
  return [
    "/*",
    "  Generated by scripts/tokens.mjs from src/tokens/tokens.json. Do not edit by hand:",
    "  edit the JSON, then run `pnpm tokens`. `pnpm check` fails while this file is stale.",
    "*/",
    ":root {" + rootLines.join("\n").replace(/^\n/, "\n"),
    "}",
    "",
    ':root[data-theme="light"] {' + lightLines.join("\n"),
    "}",
    "",
  ].join("\n");
}

// ---------- reachability ----------
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
function liveFiles() {
  const all = walk(SRC).filter((f) => /\.(astro|css|svelte|mdx|ts|js|mjs)$/.test(f));
  const resolve = (from, spec) => {
    const p = spec.startsWith("@/") ? path.join(SRC, spec.slice(2)) : spec.startsWith(".") ? path.resolve(path.dirname(from), spec) : null;
    if (!p) return null;
    for (const c of [p, p + ".astro", p + ".ts", p + ".js", p + ".css", p + ".svelte"]) if (fs.existsSync(c) && fs.statSync(c).isFile()) return c;
    return null;
  };
  const seen = new Set();
  const stack = all.filter((f) => f.startsWith(path.join(SRC, "pages")) || f.startsWith(path.join(SRC, "content")));
  while (stack.length) {
    const f = stack.pop();
    if (seen.has(f)) continue;
    seen.add(f);
    const t = fs.readFileSync(f, "utf8");
    for (const m of t.matchAll(/(?:import\s[^'"]*?from\s*|import\s*|@import\s*(?:url\()?)['"]([^'"]+)['"]/g)) { const r = resolve(f, m[1]); if (r) stack.push(r); }
  }
  return [...seen].filter((f) => /\.(astro|css|svelte)$/.test(f) && f !== CSS_PATH).sort();
}

// ---------- raw-value scan ----------
// Only lines in CSS context count: .css files, <style> blocks and inline style attributes.
const RULES = {
  color: { re: /rgba\(\s*var\(--[\w-]+\)\s*,\s*[\d.]+\s*\)|#[0-9a-fA-F]{3,8}\b|rgba?\(\s*\d[^()]*\)|hsla?\([^()]*\)|color-mix\((?:[^()]|\([^()]*\))*\)/g, why: "Use a color role from src/tokens/tokens.json, or add one." },
  "font-size": { prop: /(?:^|[\s;{])font-size\s*:\s*([^;}"`]+)/g, why: "Use a type role, or add one to tokens.json." },
  "font-weight": { prop: /(?:^|[\s;{])font-weight\s*:\s*([^;}"`]+)/g, why: "Use a weight token." },
  "line-height": { prop: /(?:^|[\s;{])line-height\s*:\s*([^;}"`]+)/g, why: "Use a leading token." },
  "letter-spacing": { prop: /(?:^|[\s;{])letter-spacing\s*:\s*([^;}"`]+)/g, why: "Use a tracking token." },
  spacing: { prop: /(?:^|[\s;{])(?:margin|padding)(?:-[a-z-]+)?\s*:\s*([^;}"`]+)|(?:^|[\s;{])(?:row-|column-)?gap\s*:\s*([^;}"`]+)/g, split: true, why: "Use a space or layout token." },
  duration: { re: /(?<![\w.-])\d*\.?\d+m?s\b/g, ctx: /transition|animation/, why: "Use a motion token." },
  easing: { re: /cubic-bezier\([^)]*\)|(?<![-\w])(?:ease-in-out|ease-in|ease-out|ease)(?![-\w])/g, ctx: /transition|animation/, why: "Use the house curve token (--ease-out)." },
};
const BANS = {
  "keyframes-outside-animations": { re: /@keyframes\s+[\w-]+/g, skip: (f) => f.endsWith("styles/animations.css"), why: "Define keyframes once in src/styles/animations.css: Astro doesn't scope @keyframes, so a second definition with the same name overrides the first site-wide." },
  "font-family": { re: /font-family\s*:(?!\s*var\(--font-[\w-]+\)\s*(?:[;}"'`]|$))/g, why: "Fonts come from the type tokens only: font-family: var(--font-…)." },
  "transition-all": { re: /transition\s*:\s*all\b/g, why: "Name the properties that animate (transform, opacity, color...)." },
  "container-literal": { re: /max-width\s*:\s*1100px/g, why: "Use var(--ds-container) or the page container." },
  "theme-storage": { re: /localStorage\.setItem\(\s*['"]theme['"]/g, ctxAll: true, why: "Theme switching belongs to one ThemeToggle." },
};
const SKIP_VALUE = /^(0|auto|inherit|initial|unset|none|normal|!important|0 !important)$/;

function cssLines(f) {
  const lines = fs.readFileSync(f, "utf8").split("\n");
  const out = [];
  let inStyle = f.endsWith(".css");
  lines.forEach((text, i) => {
    if (/<style[\s>]/.test(text)) inStyle = true;
    const inline = /style=\{?[`"']/.test(text);
    out.push({ line: i + 1, text, css: inStyle || inline });
    if (/<\/style>/.test(text)) inStyle = f.endsWith(".css");
  });
  return out;
}

function scan() {
  const counts = {}; // file -> key -> value -> n
  const where = {}; // `${file}|${key}|${value}` -> first line
  const bump = (f, key, v, line) => {
    v = v.trim().replace(/\s+/g, " ");
    if (!v || (key !== "color" && (SKIP_VALUE.test(v) || v.includes("var(")))) return;
    const fr = rel(f);
    ((counts[fr] ??= {})[key] ??= {})[v] = (counts[fr][key][v] ?? 0) + 1;
    where[`${fr}|${key}|${v}`] ??= line;
  };
  for (const f of liveFiles()) {
    let inMotion = false; // inside a transition/animation value that continues over several lines
    for (const { line, text, css } of cssLines(f)) {
      const motionLine = inMotion || /(?:transition|animation)[\w-]*\s*:/.test(text);
      inMotion = motionLine && !text.includes(";") && !text.includes("}");
      for (const [k, b] of Object.entries(BANS)) {
        if ((!css && !b.ctxAll) || b.skip?.(f)) continue;
        for (const m of text.matchAll(b.re)) bump(f, "ban:" + k, m[0], line);
      }
      if (!css || /^\s*--[\w-]+\s*:/.test(text)) continue; // token definitions are not uses
      for (const [k, r] of Object.entries(RULES)) {
        if (r.ctx && !r.ctx.test(text) && !(css && motionLine)) continue;
        if (r.prop) for (const m of text.matchAll(r.prop)) {
          const val = (m[1] ?? m[2] ?? "").trim();
          if (r.split) for (const part of val.split(/\s+(?![^(]*\))/)) bump(f, k, part, line);
          else bump(f, k, val, line);
        }
        else for (const m of text.matchAll(r.re)) bump(f, k, k === "color" ? m[0].toLowerCase() : m[0], line);
      }
    }
  }
  return { counts, where };
}

// ---------- family drift ----------
// The Cello family layer (fonts, neutral endpoints, the house curve, the reduced-motion contract)
// is vendored at src/tokens/family.json. tokens.json must use exactly those values.
function familyCheck() {
  const problems = [], warnings = [];
  if (!fs.existsSync(FAMILY_PATH)) return { problems: ["src/tokens/family.json is missing: vendor it from ~/Documents/code/cello-family"], warnings, version: null };
  const family = JSON.parse(fs.readFileSync(FAMILY_PATH, "utf8"));
  const tokens = Object.fromEntries(JSON.parse(fs.readFileSync(JSON_PATH, "utf8")).groups.flatMap((g) => g.tokens).map((t) => [t.css, t.$value]));
  const same = (a, b) => String(a).trim().toLowerCase() === String(b).trim().toLowerCase();
  const stack = (v) => String(v).split(",").map((f) => f.trim().replace(/^"|"$/g, ""));
  const expect = (ok, what) => { if (!ok) problems.push(`Family drift: ${what} (family ${family.version}). Change tokens.json, or change the family repo first.`); };
  expect(same(tokens["--ink-950"], family.neutral.ink.$value), `--ink-950 is ${tokens["--ink-950"]}, family ink is ${family.neutral.ink.$value}`);
  expect(same(tokens["--paper-100"], family.neutral.paper.$value), `--paper-100 is ${tokens["--paper-100"]}, family paper is ${family.neutral.paper.$value}`);
  expect(same(tokens["--ease-out"], family.motion["ease-out"].$value), `--ease-out is ${tokens["--ease-out"]}, the family curve is ${family.motion["ease-out"].$value}`);
  expect(stack(tokens["--font-mono"])[0] === family.type.mono.family, `--font-mono doesn't lead with ${family.type.mono.family}`);
  expect(stack(tokens["--font-read"]).some((f) => f === family.type.sans.family || f === `${family.type.sans.family} Variable`), `--font-read doesn't use ${family.type.sans.family}`);
  const motionCss = fs.readFileSync(path.join(SRC, "styles/animations.css"), "utf8");
  expect(/animation-delay:\s*var\(--motion-none\)\s*!important/.test(motionCss) && /transition-delay:\s*var\(--motion-none\)\s*!important/.test(motionCss),
    "the reduced-motion block in src/styles/animations.css no longer zeroes animation and transition delays");
  if (fs.existsSync(FAMILY_SOURCE)) {
    const source = JSON.parse(fs.readFileSync(FAMILY_SOURCE, "utf8"));
    const newer = (a, b) => { const x = a.split(".").map(Number), y = b.split(".").map(Number); for (let i = 0; i < 3; i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) > (y[i] ?? 0); return false; };
    if (newer(source.version, family.version)) warnings.push(`Cello family ${source.version} is available (vendored ${family.version}): copy ~/Documents/code/cello-family/family.json to src/tokens/family.json and re-run.`);
  }
  return { problems, warnings, version: family.version };
}

// ---------- main ----------
const css = generate();
if (flag("--baseline")) {
  const { counts } = scan();
  fs.writeFileSync(BASELINE_PATH, JSON.stringify(counts, null, 1) + "\n");
  const total = Object.values(counts).flatMap((k) => Object.values(k)).flatMap((v) => Object.values(v)).reduce((a, b) => a + b, 0);
  console.log(`raw-baseline.json written: ${total} raw values and hand-built patterns across ${Object.keys(counts).length} files.`);
} else if (flag("--check")) {
  const problems = [];
  if (!fs.existsSync(CSS_PATH) || fs.readFileSync(CSS_PATH, "utf8") !== css) problems.push("src/styles/tokens.css is out of date: run pnpm tokens");
  const baseline = fs.existsSync(BASELINE_PATH) ? JSON.parse(fs.readFileSync(BASELINE_PATH, "utf8")) : {};
  const { counts, where } = scan();
  for (const [f, keys] of Object.entries(counts)) for (const [k, vals] of Object.entries(keys)) for (const [v, n] of Object.entries(vals)) {
    const allowed = baseline[f]?.[k]?.[v] ?? 0;
    if (n > allowed) {
      const why = k.startsWith("ban:") ? BANS[k.slice(4)].why : RULES[k].why;
      problems.push(`${f}:${where[`${f}|${k}|${v}`]}: new ${k.startsWith("ban:") ? "hand-built pattern" : "raw " + k} ${v}${n - allowed > 1 ? ` (+${n - allowed})` : ""}. ${why}`);
    }
  }
  const family = familyCheck();
  problems.push(...family.problems);
  family.warnings.forEach((w) => console.warn(`warning: ${w}`));
  if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
  console.log(`Tokens are up to date, match Cello family ${family.version}, and there are no new raw values or hand-built keyframes, fonts, transitions, containers or theme storage.`);
} else {
  fs.writeFileSync(CSS_PATH, css);
  console.log("src/styles/tokens.css written from src/tokens/tokens.json");
}
